CLASS_NAME = {"M": "Mandatory", "C": "Conditional", "O": "Optional"}


def artefacts():
    out = []
    fed_by = {no: [] for no in F}
    for no, d in F.items():
        for t in d["feeds"]:
            fed_by[t].append(no)
    for no, title, code, ext, doms, focus, appr in REGISTER:
        if no not in F:
            continue
        d = F[no]
        out.append(dict(no=no, title=title, code=code, id=doc_id(code), ext=ext, domains=doms, focus=focus,
                        cat=d["cat"], catName=CATS[d["cat"]][0], catRule=CATS[d["cat"]][1],
                        tailor={"Low": d["tailor"][0], "Medium": d["tailor"][1], "High": d["tailor"][2]},
                        cls=CLASS_NAME[d["tailor"][1]], cond=d["cond"],
                        created=d["created"], gate=d["gate"], trigger=d["trigger"],
                        owner=d["owner"], approver=d["approver"], consulted=d["consulted"],
                        baseline=d["baseline"], cadence=d["cadence"],
                        feeds=d["feeds"], fedBy=sorted(fed_by[no]), accept=d["accept"]))
    return out


